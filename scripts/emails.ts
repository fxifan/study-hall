/**
 * Writes the bilingual Supabase Auth email templates, and optional previews of every automated
 * parent email. Sends nothing.
 *   npm run emails                 -> supabase/templates/{magic_link,confirmation}.html
 *   npm run emails -- --preview    -> also email-previews/*.html and *.txt (gitignored) to open locally
 * Hosted project: paste each template into Supabase > Authentication > Email Templates (Magic Link,
 * Confirm signup) with the subject printed below. The copy lives in src/i18n/dictionaries (emails).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { sampleReports } from "../src/app/[lang]/_landing/sample-data";
import { DEFAULT_TIMETABLE } from "../src/lib/timetable";
import { authEmail, reportEmail } from "../src/lib/email/templates";

const GENERATED = "<!-- Generated by `npm run emails` from src/lib/email/templates.ts; edit the source, not this file. -->\n";

const templates = { magic_link: authEmail("login"), confirmation: authEmail("signup") };
for (const [name, email] of Object.entries(templates)) {
  writeFileSync(`supabase/templates/${name}.html`, GENERATED + email.html);
  console.log(`supabase/templates/${name}.html  subject: ${email.subject}`);
}

if (process.argv.includes("--preview")) {
  mkdirSync("email-previews", { recursive: true });
  const origin = "https://study-hall-murex.vercel.app";
  const SAMPLES = sampleReports(DEFAULT_TIMETABLE[0]);
  const previews = {
    login: templates.magic_link,
    signup: templates.confirmation,
    "report-attended": reportEmail(SAMPLES.attended.report, origin),
    "report-absent": reportEmail(SAMPLES.absent.report, origin),
  };
  for (const [name, email] of Object.entries(previews)) {
    writeFileSync(`email-previews/${name}.html`, email.html);
    writeFileSync(`email-previews/${name}.txt`, `Subject: ${email.subject}\n\n${email.text}`);
  }
  console.log(`Previews in email-previews/ (${Object.keys(previews).join(", ")})`);
}
